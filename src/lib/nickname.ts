function pick<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}

/** 오픈채팅식 익명 닉네임 (감정·동작 + 동물). */
export function randomNick(): string {
  return `${pick(ADJECTIVES)} ${pick(ANIMALS)}`;
}
